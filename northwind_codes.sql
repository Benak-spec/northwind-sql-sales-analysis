-- 13. Who are the top 3 customers by revenue in each country?
WITH customer_revenue AS (
SELECT SUM(order_details.unit_price * order_details.quantity * (1-order_details.discount)) AS revenue,
customers.country, customers.contact_name FROM order_details INNER JOIN orders
ON order_details.order_id = orders.order_id INNER JOIN customers 
ON orders.customer_id = customers.customer_id 
GROUP BY customers.country, customers.contact_name
),
ranked_customers AS (
SELECT country, contact_name, revenue, RANK() OVER(PARTITION BY country
ORDER BY revenue) AS customer_rank FROM customer_revenue
)
SELECT country, contact_name, revenue, customer_rank FROM ranked_customers
WHERE customer_rank <= 3
ORDER BY revenue,country DESC
-- Insight: To identify top 3 customers based on their country.

-- 14. Show the top 2 products by revenue in each category
WITH product_revenue AS (
SELECT products.product_name, categories.category_name, SUM(order_details.unit_price * order_details.quantity *(1-order_details.discount)) AS revenue
FROM order_details INNER JOIN products ON order_details.product_id = products.product_id
INNER JOIN categories ON products.category_id = categories.category_id
GROUP BY categories.category_name, products.product_name
), ranked_products AS (
SELECT product_name, category_name, revenue, RANK() OVER(PARTITION BY category_name ORDER BY revenue DESC)
AS product_rank FROM product_revenue
)
SELECT product_name, category_name, revenue, product_rank FROM ranked_products
WHERE product_rank <= 2
ORDER BY revenue DESC
-- Insight: To identify the top 2 performing products within each category.
