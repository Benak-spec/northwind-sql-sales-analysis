-- 11. Classify customers based on total revenue
SELECT customers.contact_name, SUM(order_details.unit_price * order_details.quantity * (1-order_details.discount)) AS revenue,
CASE  
WHEN SUM(order_details.unit_price * order_details.quantity * (1-order_details.discount)) BETWEEN 1 AND 5000 THEN 'Cheapskates'
WHEN SUM(order_details.unit_price * order_details.quantity * (1-order_details.discount)) BETWEEN 5001 AND 10000 THEN 'Average Customers'
ELSE 'Top Customers'
END AS customer_priority
FROM order_details INNER JOIN orders ON order_details.order_id = orders.order_id INNER JOIN 
customers ON orders.customer_id = customers.customer_id
GROUP BY contact_name
ORDER BY customer_priority
-- Insight: Groups customers based on revenue.

