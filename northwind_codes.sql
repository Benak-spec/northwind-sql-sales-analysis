-- 3. Show total revenue by product (with product name), sorted highest to lowest.
SELECT product_name,SUM(order_details.unit_price * order_details.quantity * (1-order_details.discount))
AS revenue_total FROM products INNER JOIN order_details
ON products.product_id = order_details.product_id
GROUP BY products.product_name
ORDER BY revenue_total DESC
-- Insight: The best selling product is Côte de Blaye with a revenue of 141396.7356273254.

-- 4. Show total revenue generated by each customer (with customer name), sorted highest to lowest.
SELECT customers.contact_name,SUM(order_details.unit_price * order_details.quantity * (1-order_details.discount))
AS total_revenue
FROM customers INNER JOIN orders
ON customers.customer_id = orders.customer_id INNER JOIN order_details
ON orders.order_id = order_details.order_id
GROUP BY customers.contact_name
ORDER BY total_revenue DESC
-- Insight: Most revenue generated customer is Horst Kloss with 110277.30503039382.

-- 5. Show total number of orders placed by each customer, with customer name, sorted from highest to lowest.
SELECT COUNT(orders.order_id) AS total_orders,customers.contact_name FROM orders INNER JOIN customers
ON orders.customer_id = customers.customer_id
GROUP BY customers.contact_name
ORDER BY total_orders DESC
-- Insight: The highest orders are from Jose Pavarotti

-- 6. Show the total revenue for each product category, with category name, sorted highest to lowest.
SELECT categories.category_name,products.category_id, SUM(order_details.unit_price * order_details.quantity * (1-discount))
AS total_revenue
FROM categories INNER JOIN products
ON categories.category_id = products.category_id INNER JOIN order_details
ON products.product_id = order_details.product_id
GROUP BY categories.category_name,products.category_id
ORDER BY total_revenue DESC
-- Insight: Product category had the most generated revenue was beverages.

-- 7. Show total revenue for each month, sorted by year and month.
SELECT TO_CHAR(orders.order_date,'YYYY-MM') AS order_month, SUM(order_details.unit_price * order_details.quantity * (1-order_details.discount)) 
AS total_revenue
FROM orders INNER JOIN order_details ON orders.order_id = order_details.order_id
GROUP BY TO_CHAR(orders.order_date,'YYYY-MM')
ORDER BY order_month
-- Insight: This code helps to find the sales trend over time.

-- 8. Show the top 5 customers in the USA by total revenue, with company name.
SELECT SUM(order_details.unit_price * order_details.quantity * (1-order_details.discount)) AS revenue,
customers.company_name
FROM order_details INNER JOIN orders ON order_details.order_id = orders.order_id INNER JOIN customers
ON orders.customer_id = customers.customer_id
WHERE customers.country LIKE 'USA'
GROUP BY customers.company_name
ORDER BY revenue DESC
LIMIT 5
-- Insight: Used to return the top 5 customers in USA. 

-- 9. Show countries with more than 5 customers.
